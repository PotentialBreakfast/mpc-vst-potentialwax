#!/usr/bin/env python3
"""make_kit_template.py: turns a drum program saved by MPC OS 3.10.1 into src/kit_template.h, the pieces SAVE KIT
(src/kit_writer.h) writes a new drum program from.

    tools/make_kit_template.py <a drum program .xpm saved on the MPC> [src/kit_template.h]

A 3.10.1 program (.xpm) is gzip of 5 header lines (ACVS, MPC version, SerialisableProgramData, json, Linux) and a
cereal JSON body (data.version 6). Its 128 pads (data.drum.instruments) differ, when empty, only in random seeds; a pad
with a sample has it on layer 1 (sampleName, sampleFile, sliceInfo.End = frames - 1) and its own tempo, and the sample
is listed in data.samples. The samples sit in "<program>_[ProgramData]/" beside the .xpm. Device-verified 2026-11-13
(MPC One, MPC OS 3.10.1.12): a program written this way loads and plays.

The template keeps the program exactly as the MPC wrote it (key order, 4-space indent) with every pad empty, and marks
the fields SAVE KIT fills: @PAD@ (all 128 pads), and in one pad and one sample entry @TEMPO@, @NAME@, @FILE@, @END@,
@SEED@, @RSEED@. Nothing of the original program's own samples is kept."""
import copy, gzip, json, sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "src/kit_template.h"
raw = gzip.open(src, "rb").read().decode("utf-8")
head, body = raw.split("{", 1)
head_lines = head.rstrip("\n").split("\n")
assert len(head_lines) == 5 and head_lines[0] == "ACVS" and head_lines[2] == "SerialisableProgramData", head_lines
doc = json.loads("{" + body)
d = doc["data"]
assert d["version"] == 6, d["version"]
ins = d["drum"]["instruments"]
assert len(ins) == 128
empty = next(x for x in ins if not x["layersv"][0].get("sampleName"))

pad = copy.deepcopy(empty)
pad["tempo"] = "@TEMPO@"
if "randomPlaySeed" in pad:
    pad["randomPlaySeed"] = "@RSEED@"
for l in pad["layersv"]:
    l["sliceIncrementRngSeed"] = "@SEED@"
l0 = pad["layersv"][0]
l0["sampleName"] = "@NAME@"
l0["sampleFile"] = "@FILE@"
l0["sliceInfo"]["End"] = "@END@"
sample = {"version": 1, "name": "@NAME@", "path": "@FILE@", "loadImpl": 0,
          "metadata": {"tempo": "@TEMPO@", "rootNote": 60, "tune": 0.0, "key": "C Major"}}
d["name"] = "@PROGRAM@"
d["drum"]["instruments"] = ["@PADS@"]
d["samples"] = ["@SAMPLES@"]
text = "\n".join(head_lines) + "\n" + json.dumps(doc, indent=4) + "\n"


def item_indent(marker):
    line = next(l for l in text.split("\n") if marker in l)
    return line[: len(line) - len(line.lstrip())]


pad_ind, smp_ind = item_indent('"@PADS@"'), item_indent('"@SAMPLES@"')


def block(obj, ind):
    t = json.dumps(obj, indent=4)
    return "\n".join((ind + l) for l in t.split("\n"))


pad_txt = block(pad, pad_ind)
smp_txt = block(sample, smp_ind)
# numbers go in without quotes, names as JSON strings
for k in ("@TEMPO@", "@END@", "@SEED@", "@RSEED@"):
    pad_txt = pad_txt.replace('"%s"' % k, k)
    smp_txt = smp_txt.replace('"%s"' % k, k)
pad_txt = pad_txt.replace('"@NAME@"', "@NAME@").replace('"@FILE@"', "@FILE@")
smp_txt = smp_txt.replace('"@NAME@"', "@NAME@").replace('"@FILE@"', "@FILE@")
text = text.replace('"@PROGRAM@"', "@PROGRAM@")
a, rest = text.split(pad_ind + '"@PADS@"', 1)
b, c = rest.split(smp_ind + '"@SAMPLES@"', 1)


def cstr(name, s):
    out = ["static const char %s[] =" % name]
    for line in s.split("\n")[:-1]:
        out.append('    "%s\\n"' % line.replace("\\", "\\\\").replace('"', '\\"'))
    last = s.split("\n")[-1]
    out.append('    "%s";' % last.replace("\\", "\\\\").replace('"', '\\"'))
    return "\n".join(out)


h = ["/* Generated by tools/make_kit_template.py from a drum program saved by MPC OS %s: do not edit. */" % head_lines[1],
     "/* KIT_HEAD + KIT_PAD x 128 (\",\\n\" between) + KIT_MID + KIT_SAMPLE x n (\",\\n\" between) + KIT_TAIL */",
     cstr("KIT_HEAD", a), cstr("KIT_PAD", pad_txt), cstr("KIT_MID", b), cstr("KIT_SAMPLE", smp_txt), cstr("KIT_TAIL", c), ""]
open(out, "w").write("\n".join(h))
print("wrote %s: head %d, pad %d, mid %d, sample %d, tail %d chars" % (out, len(a), len(pad_txt), len(b), len(smp_txt), len(c)))
